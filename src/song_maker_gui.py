#!/usr/bin/env python3
"""Simple GUI for choosing a MIDI song, target board, and buzzer pin.

Run from the repository root with: python src/song_maker_gui.py
Requires tkinter (usually included with Python) and mido.
"""
from __future__ import annotations

import re
import tkinter as tk
from pathlib import Path
from tkinter import filedialog, messagebox, ttk

from chiptune_converter import make_monophonic, read_midi_notes, write_header

ROOT = Path(__file__).resolve().parent.parent
MUSIC_DIR = ROOT / "music"
OUTPUT_DIR = ROOT / "generated"

# Labels are explicit about the core/runtime expected by the generated sketch.
BOARDS = {
    "Arduino Uno / Nano (AVR)": {"pins": [str(i) for i in range(2, 14)], "default": "8"},
    "Arduino Mega 2560 (AVR)": {"pins": [str(i) for i in range(2, 54)], "default": "8"},
    "Arduino Leonardo / Micro (AVR)": {"pins": [str(i) for i in range(2, 14)], "default": "8"},
    "ESP32 DevKit (Arduino core)": {"pins": [str(i) for i in range(2, 23)] + [str(i) for i in range(25, 28)] + [str(i) for i in range(32, 34)], "default": "25"},
    "ESP8266 NodeMCU (Arduino core)": {"pins": ["0", "2", "4", "5", "12", "13", "14", "15", "16"], "default": "5"},
    "Raspberry Pi Pico / RP2040 (Arduino-Pico core)": {"pins": [str(i) for i in range(0, 23)], "default": "15"},
    "Raspberry Pi Pico 2 / RP2350 (Arduino-Pico core)": {"pins": [str(i) for i in range(0, 30)], "default": "15"},
}

SKETCH_TEMPLATE = r'''// Generated by 8-bit Song Maker for Buzzer.
// Target: {board}
// Buzzer signal: GPIO/pin {pin}; buzzer GND -> board GND.
// Use a PASSIVE buzzer. Board/core support for tone() can vary.

#include <Arduino.h>
#include "song.h"

void playSong() {{
  for (size_t i = 0; i < SONG_LENGTH; ++i) {{
    if (song[i].freq > 0) {{
      tone(BUZZER_PIN, song[i].freq, song[i].time);
    }} else {{
      noTone(BUZZER_PIN);
    }}
    delay(song[i].time);
    noTone(BUZZER_PIN);
    delay(10);
  }}
}}

void setup() {{
  pinMode(BUZZER_PIN, OUTPUT);
  playSong();
  noTone(BUZZER_PIN);
}}

void loop() {{
  // Song plays once after reset. Call playSong() here to repeat it.
}}
'''


class SongMakerApp:
    def __init__(self, root: tk.Tk) -> None:
        self.root = root
        root.title("8-bit Song Maker for Buzzer")
        root.geometry("690x430")
        root.minsize(600, 390)

        self.song_var = tk.StringVar()
        self.custom_song_var = tk.StringVar()
        self.board_var = tk.StringVar(value="Raspberry Pi Pico / RP2040 (Arduino-Pico core)")
        self.pin_var = tk.StringVar(value="15")
        self.output_var = tk.StringVar(value=str(OUTPUT_DIR))
        self.repeat_var = tk.BooleanVar(value=False)

        main = ttk.Frame(root, padding=18)
        main.pack(fill="both", expand=True)
        main.columnconfigure(1, weight=1)

        ttk.Label(main, text="Song").grid(row=0, column=0, sticky="w", padx=(0, 12), pady=8)
        self.song_box = ttk.Combobox(main, textvariable=self.song_var, state="readonly")
        self.song_box.grid(row=0, column=1, sticky="ew", pady=8)
        ttk.Button(main, text="Browse MIDI…", command=self.browse_song).grid(row=0, column=2, padx=(8, 0), pady=8)

        ttk.Label(main, text="Target board").grid(row=1, column=0, sticky="w", padx=(0, 12), pady=8)
        self.board_box = ttk.Combobox(main, textvariable=self.board_var, values=list(BOARDS), state="readonly")
        self.board_box.grid(row=1, column=1, columnspan=2, sticky="ew", pady=8)
        self.board_box.bind("<<ComboboxSelected>>", self.on_board_changed)

        ttk.Label(main, text="Buzzer pin / GPIO").grid(row=2, column=0, sticky="w", padx=(0, 12), pady=8)
        self.pin_box = ttk.Combobox(main, textvariable=self.pin_var, state="readonly")
        self.pin_box.grid(row=2, column=1, sticky="w", pady=8)
        ttk.Label(main, text="Use the board's GPIO/pin number, not the physical header position.").grid(
            row=3, column=1, columnspan=2, sticky="w"
        )

        ttk.Label(main, text="Output folder").grid(row=4, column=0, sticky="w", padx=(0, 12), pady=8)
        ttk.Entry(main, textvariable=self.output_var).grid(row=4, column=1, sticky="ew", pady=8)
        ttk.Button(main, text="Choose…", command=self.browse_output).grid(row=4, column=2, padx=(8, 0), pady=8)

        self.status = ttk.Label(main, text="Choose a song and board, then generate an Arduino sketch.", wraplength=620)
        self.status.grid(row=5, column=0, columnspan=3, sticky="w", pady=(14, 10))

        ttk.Button(main, text="Generate sketch", command=self.generate).grid(
            row=6, column=0, columnspan=3, sticky="ew", ipady=8, pady=(8, 0)
        )
        ttk.Label(
            main,
            text="Output: a ready-to-open .ino sketch plus song.h. MIDI chords are reduced to one note at a time.",
            wraplength=620,
        ).grid(row=7, column=0, columnspan=3, sticky="w", pady=(12, 0))

        self.song_paths: dict[str, Path] = {}
        self.refresh_songs()
        self.on_board_changed()

    def refresh_songs(self) -> None:
        paths = sorted(MUSIC_DIR.glob("*.mid")) + sorted(MUSIC_DIR.glob("*.midi"))
        self.song_paths = {p.name: p for p in paths}
        self.song_box["values"] = list(self.song_paths)
        if paths:
            self.song_var.set(paths[0].name)
        else:
            self.song_var.set("")

    def browse_song(self) -> None:
        filename = filedialog.askopenfilename(
            title="Choose a MIDI file",
            filetypes=[("MIDI files", "*.mid *.midi"), ("All files", "*.*")],
            initialdir=str(MUSIC_DIR if MUSIC_DIR.exists() else ROOT),
        )
        if filename:
            path = Path(filename)
            self.song_paths[path.name] = path
            self.song_box["values"] = list(self.song_paths)
            self.song_var.set(path.name)

    def browse_output(self) -> None:
        directory = filedialog.askdirectory(title="Choose output folder", initialdir=self.output_var.get() or str(ROOT))
        if directory:
            self.output_var.set(directory)

    def on_board_changed(self, _event=None) -> None:
        profile = BOARDS[self.board_var.get()]
        self.pin_box["values"] = profile["pins"]
        # Changing boards should select that board's recommended default pin.
        self.pin_var.set(profile["default"])

    def generate(self) -> None:
        song_path = self.song_paths.get(self.song_var.get())
        if song_path is None or not song_path.is_file():
            messagebox.showerror("Choose a song", "Select a MIDI file or use Browse MIDI.")
            return

        try:
            pin = int(self.pin_var.get())
        except ValueError:
            messagebox.showerror("Invalid pin", "Choose a valid pin number for this board.")
            return

        try:
            notes = make_monophonic(read_midi_notes(song_path))
        except (OSError, ValueError, RuntimeError) as exc:
            messagebox.showerror("MIDI error", f"Could not convert this MIDI file:\n{exc}")
            return
        if not notes:
            messagebox.showerror("No playable notes", "No usable notes were found in this MIDI file.")
            return

        board = self.board_var.get()
        safe_song = re.sub(r"[^A-Za-z0-9_-]+", "_", song_path.stem).strip("_") or "song"
        safe_board = re.sub(r"[^A-Za-z0-9_-]+", "_", board).strip("_")
        destination = Path(self.output_var.get()).expanduser() / f"{safe_song}_{safe_board}"
        try:
            destination.mkdir(parents=True, exist_ok=True)
            write_header(destination / "song.h", notes, pin)
            sketch = SKETCH_TEMPLATE.format(board=board, pin=pin)
            (destination / f"{safe_song}_{safe_board}.ino").write_text(sketch, encoding="utf-8")
        except OSError as exc:
            messagebox.showerror("Write error", f"Could not create output files:\n{exc}")
            return

        self.status.config(text=f"Created {len(notes)} note segments in:\n{destination}")
        messagebox.showinfo(
            "Sketch generated",
            f"Created:\n{destination}\n\nOpen the .ino file in Arduino IDE.\n"
            "Check the board selection, installed board core, and wiring before uploading.",
        )


def main() -> None:
    try:
        import mido  # noqa: F401
    except ImportError:
        print("Missing dependency. Install it with: python -m pip install mido")
        raise SystemExit(1)

    root = tk.Tk()
    SongMakerApp(root)
    root.mainloop()


if __name__ == "__main__":
    main()
